CREATE TABLE equipment_categories
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ
);

CREATE UNIQUE INDEX ux_equipment_categories_name ON equipment_categories (lower(name)) WHERE deleted_at IS NULL;

CREATE TABLE equipments
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    code                  VARCHAR(7)   NOT NULL,
    serial_number         VARCHAR(50)  NOT NULL,
    description           VARCHAR(255),
    availability          VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE',
    equipment_condition   VARCHAR(20)  NOT NULL DEFAULT 'GOOD',
    condition_notes       VARCHAR(255),
    equipment_category_id BIGINT       NOT NULL REFERENCES equipment_categories (id),
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at            TIMESTAMPTZ,
    CONSTRAINT ck_equipments_availability CHECK (availability IN ('AVAILABLE', 'LOANED', 'IN_MAINTENANCE', 'RETIRED')),
    CONSTRAINT ck_equipments_condition CHECK (equipment_condition IN ('GOOD', 'WORN', 'DAMAGED'))
);

CREATE UNIQUE INDEX ux_equipments_code ON equipments (code) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX ux_equipments_serial_number ON equipments (serial_number) WHERE deleted_at IS NULL;
CREATE INDEX ix_equipments_category ON equipments (equipment_category_id);
