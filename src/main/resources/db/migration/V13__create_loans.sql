CREATE TABLE loans
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(7)   NOT NULL,
    requester_id        BIGINT       NOT NULL REFERENCES users (id),
    kit_id              BIGINT REFERENCES kits (id),
    status              VARCHAR(20)  NOT NULL DEFAULT 'PENDING_PICKUP',
    scheduled_pickup_at TIMESTAMPTZ  NOT NULL,
    picked_up_at        TIMESTAMPTZ,
    scheduled_return_at TIMESTAMPTZ  NOT NULL,
    returned_at         TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ,
    registered_by_id    BIGINT       NOT NULL REFERENCES users (id),
    delivered_by_id     BIGINT REFERENCES users (id),
    received_by_id      BIGINT REFERENCES users (id),
    notes               VARCHAR(255),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ,
    CONSTRAINT ck_loans_status CHECK (status IN ('PENDING_PICKUP', 'ACTIVE', 'RETURNED', 'CANCELLED')),
    CONSTRAINT ck_loans_schedule CHECK (scheduled_return_at > scheduled_pickup_at)
);

CREATE UNIQUE INDEX ux_loans_code ON loans (code) WHERE deleted_at IS NULL;
CREATE INDEX ix_loans_requester ON loans (requester_id);
CREATE INDEX ix_loans_status ON loans (status);

CREATE TABLE loan_items
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id          BIGINT      NOT NULL REFERENCES loans (id),
    equipment_id     BIGINT      NOT NULL REFERENCES equipments (id),
    pickup_condition VARCHAR(20) NOT NULL,
    return_condition VARCHAR(20),
    CONSTRAINT ck_loan_items_pickup_condition CHECK (pickup_condition IN ('GOOD', 'WORN', 'DAMAGED')),
    CONSTRAINT ck_loan_items_return_condition CHECK (return_condition IN ('GOOD', 'WORN', 'DAMAGED')),
    CONSTRAINT ux_loan_items_loan_equipment UNIQUE (loan_id, equipment_id)
);

CREATE INDEX ix_loan_items_equipment ON loan_items (equipment_id);
