CREATE TABLE kits
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    code        VARCHAR(7)   NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ
);

CREATE UNIQUE INDEX ux_kits_code ON kits (code) WHERE deleted_at IS NULL;

CREATE TABLE kit_items
(
    kit_id       BIGINT NOT NULL REFERENCES kits (id),
    equipment_id BIGINT NOT NULL REFERENCES equipments (id),
    PRIMARY KEY (kit_id, equipment_id)
);

CREATE UNIQUE INDEX ux_kit_items_equipment ON kit_items (equipment_id);
